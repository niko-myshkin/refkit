// Подмена lucide-react: vite отдаёт этот файл на любой import из 'lucide-react' (см. vite.config.ts). Иконки, что есть в мягком наборе, рисуются им, пока он включён;
// остальные и обычный режим — оригинальный Lucide. Отключить подмену целиком: убрать alias в vite.config.ts
export * from 'lucide-react-real'

function soft(name: string, Original: LucideIcon): LucideIcon {
  const Icon = forwardRef<SVGSVGElement, LucideProps>((props, ref) => {
    const pack = useIconPack()
    // Solar (look & feel 2026-10-27): готовые тонкие иконки со своими штрихами в самом коде; цвет — currentColor, толщину не меняем
    if (pack === 'solar' && SOLAR[name]) {
      const { size = 24, color, strokeWidth: _w, absoluteStrokeWidth: _a, className, children: _c, style, ...rest } = props
      return <svg ref={ref} xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 24 24" fill="none" className={className ? `lucide ${className}` : 'lucide'} style={color ? { color, ...style } : style} {...rest} dangerouslySetInnerHTML={{ __html: SOLAR[name] }} />
    }
    const inner = pack === 'soft' ? SOFT[name] : undefined
    if (!inner) return <Original ref={ref} {...props} />
    const { size = 24, color, strokeWidth: _stroke, absoluteStrokeWidth: _absolute, className, children: _children, ...rest } = props
    return <svg ref={ref} xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 24 24" fill="none" stroke={color ?? 'currentColor'} strokeWidth={1.9} strokeLinecap="round" strokeLinejoin="round" className={className ? `lucide ${className}` : 'lucide'} {...rest} dangerouslySetInnerHTML={{ __html: inner }} />
  })
  Icon.displayName = name
  return Icon as unknown as LucideIcon
}

