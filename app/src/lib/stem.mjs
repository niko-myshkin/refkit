// «шрифты» находит «шрифт», «дизайн-система» — «дизайн-системы». Обычный .mjs, чтобы его читал и Node без сборки.
// Отрезаем падежное окончание; короче трёх букв не режем, иначе «дом» превратится в «д» и найдёт всё подряд.
export function stem(word) {
  const cut = word.replace(/(ами|ями|ого|его|ому|ему|ыми|ими|ой|ей|ий|ый|ая|яя|ое|ее|ые|ие|ую|юю|ов|ев|ам|ям|ах|ях|ом|ем|[аяоеуюыиьй])$/, '')
  return cut.length >= 3 ? cut : word
}

// Слова запроса → основы: нижний регистр, «ё» как «е», разделители не буквы и не цифры
export const queryStems = (query) => String(query ?? '').toLowerCase().replace(/ё/g, 'е').split(/[^\p{L}\d]+/u).filter(Boolean).map(stem)
